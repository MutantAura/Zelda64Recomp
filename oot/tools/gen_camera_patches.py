#!/usr/bin/env python3
# Generates oot/patches/camera_mode_patches.c, which patches OoT's player camera modes to support the analog (dual stick) camera.
#
# Each patched camera mode is copied from the decomp's z_camera.c with a hook inserted right before the final eye position is
# computed from the eye's VecGeo (the same place Majora's Mask's analog camera patches override the pitch and yaw).
# Usage: oot/tools/gen_camera_patches.py lib/oot-decomp oot/patches/camera_mode_patches.c
# The decomp's sources aren't UTF-8, so they're read and written as latin-1 to preserve their bytes.
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from extract_func import extract

# Camera modes used while controlling the player in normal gameplay.
PATCHED_MODES = ["Camera_Normal1", "Camera_Normal3", "Camera_Jump2", "Camera_Jump3", "Camera_Parallel1"]

FUNC_DEF_RE = re.compile(r"^(?:static\s+)?((?:[A-Za-z_][\w\s\*]*?))\s*\b(\w+)\(([^;{)]*)\)\s*\{", re.MULTILINE)
EYE_NEXT_RE = re.compile(r"\*eyeNext = Camera_AddVecGeoToVec3f\(at, &(\w+)\);")

def main():
    decomp = Path(sys.argv[1])
    camera_c = decomp / "src/code/z_camera.c"
    text = camera_c.read_text(encoding="latin-1")

    # Collect the macros defined at the top of z_camera.c, along with the conditionals around them so that
    # only the definitions for the configured version and debug settings are used.
    first_func = FUNC_DEF_RE.search(text).start()
    macros = []
    in_macro = False
    for line in text[:first_func].splitlines():
        if line.startswith("#define") or in_macro or re.match(r"#\s*(if|ifdef|ifndef|elif|else|endif)\b", line):
            macros.append(line)
            in_macro = line.endswith("\\")

    # Generate prototypes for every function in z_camera.c, as many are only declared in that file.
    prototypes = []
    for match in FUNC_DEF_RE.finditer(text):
        ret, name, args = match.group(1).strip(), match.group(2), match.group(3)
        if ret in ("if", "else", "while", "for", "switch", "return") or name in PATCHED_MODES:
            continue
        prototypes.append(f"{ret} {name}({args});")

    out = [
        "// Autogenerated by oot/tools/gen_camera_patches.py, do not edit.",
        '#include "camera_patches.h"',
        "",
        "// Macros from z_camera.c",
    ]
    out += macros
    out += ["", "// Functions from z_camera.c"]
    out += prototypes
    # Types and data from z_camera_data.inc.c
    data_text = (decomp / "src/code/z_camera_data.inc.c").read_text(encoding="latin-1")
    types_start = data_text.index("typedef struct CameraModeValue")
    types_end = data_text.index("} CameraSetting;") + len("} CameraSetting;")
    out += ["", "// Types from z_camera_data.inc.c", data_text[types_start:types_end], ""]
    out += ["extern CameraSetting sCameraSettings[];", "extern s32 sUpdateCameraDirection;", "extern s32 sCameraInterfaceField;", ""]

    for mode in PATCHED_MODES:
        func = extract(str(camera_c), mode)
        matches = list(EYE_NEXT_RE.finditer(func))
        if not matches:
            raise SystemExit(f"Couldn't find eye position calculation in {mode}")
        match = matches[-1]
        var = match.group(1)
        hook = (f"// @recomp Apply the analog camera's rotation if it's active.\n"
                f"    analog_cam_apply(camera, &{var});\n    ")
        # Find the start of the line containing the eye calculation to insert the hook with correct indentation.
        line_start = func.rfind("\n", 0, match.start()) + 1
        indent = func[line_start:match.start()]
        func = func[:match.start()] + hook.replace("\n    ", "\n" + indent) + func[match.start():]
        # Replace the decomp's stack padding macros with uniquely named variables.
        pad_index = iter(range(1000))
        func = re.sub(r"STACK_PADS?\((\w+)(?:, (\d+))?\);",
                      lambda m: f"{m.group(1)} pad{next(pad_index)}" + (f"[{m.group(2)}];" if m.group(2) else ";"), func)
        out.append(f"// @recomp Patched for the analog camera.")
        out.append("RECOMP_PATCH " + func)
        out.append("")

    Path(sys.argv[2]).write_text("\n".join(out), encoding="latin-1", newline="\n")

if __name__ == "__main__":
    main()
